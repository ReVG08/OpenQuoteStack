export const localized = (
  e: Estimator,
  locale: Locale,
  key: string,
  fallback: string,
) => e.translations?.[locale]?.[key] ?? fallback;
export const reference = (id: string) => `OQS-${id.slice(-8).toUpperCase()}`;
export const dateLabel = (
  date: Date | string,
  locale: Locale,
  timezone = "UTC",
) =>
  new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeZone: timezone,
  }).format(new Date(date));
